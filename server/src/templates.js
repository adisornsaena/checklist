const checks = (id, title, items, extra = {}) => ({
  type: 'checks',
  id,
  title,
  items: items.map((label, i) => ({ id: `${id}${i + 1}`, label })),
  ...extra,
});
// steps: [label, optionsKey | options[], { amount } ]
const steps = (id, title, items) => ({
  type: 'steps',
  id,
  title,
  items: items.map(([label, options = 'done', extra = {}], i) => ({
    id: `${id}${i + 1}`,
    label,
    options: typeof options === 'string' ? OPTS[options] : options,
    ...extra,
  })),
});
const fields = (id, title, list) => ({ type: 'fields', id, title, fields: list });

